# Exercício 2
# Imagine a produção de frutas em uma feira. Desejo apresentar as frutas banana, manga, melancia, abacaxi
# com uma quantidade de 10 bananas, 5 mangas, 10 melancias e 13 abacaxis

print("\nBananas:")
for banana in range(1,11):
    print("banana", banana)
print("\nMangas:")
for mangas in range(1,6):
    print("manga", mangas)
print("\nMelancias:")
for melancias in range(1,11):
    print("melancia", melancias)
print("\nAbacaxis:")
for abacaxis in range(1,14):
    print("abacaxi", abacaxis)


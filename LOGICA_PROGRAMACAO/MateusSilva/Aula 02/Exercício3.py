subtracao = num1 - num2
multiplicacao = num1 * num2
divisao = num1 / num2

print ("\n A soma entre o primeiro número e o segundo é igual a:", soma)
print ("\n A subtração entre o primeiro número e o segundo é igual a:", subtracao)
print ("\n A multiplicação entre o primeiro número e o segundo é igual a:", multiplicacao)
print ("\n A divisão entre o primeiro número e o segundo é igual a:", divisao)

